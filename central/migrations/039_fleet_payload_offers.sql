-- New offer-aware bases receive only inert Player payloads. Historical schema-1
-- offers remain frozen and readable while older boot trees finish their boot.
ALTER TABLE fleet_boot_offers
    ADD COLUMN offer_sequence BIGINT GENERATED BY DEFAULT AS IDENTITY,
    ADD COLUMN offer_schema INTEGER NOT NULL DEFAULT 1 CHECK (offer_schema IN (1, 2)),
    ADD COLUMN app_format TEXT CHECK (app_format = 'pw-player-data-v1'),
    ADD COLUMN app_base_abi TEXT CHECK (app_base_abi ~ '^sha256:[0-9a-f]{64}$'),
    ADD CONSTRAINT fleet_payload_offer_complete CHECK (
        (offer_schema = 1 AND app_format IS NULL AND app_base_abi IS NULL)
        OR
        (offer_schema = 2 AND
         ((app_status = 'selected' AND app_format IS NOT NULL AND app_base_abi IS NOT NULL)
          OR (app_status <> 'selected' AND app_format IS NULL AND app_base_abi IS NULL))));

-- Existing rows predate the sequence. Assign them a deterministic display order;
-- the identity's next value already follows the number of backfilled rows.
WITH ranked AS (
    SELECT offer_id, row_number() OVER (ORDER BY created_at, offer_id) AS n
    FROM fleet_boot_offers
)
UPDATE fleet_boot_offers AS offers SET offer_sequence = ranked.n
FROM ranked WHERE ranked.offer_id = offers.offer_id;

ALTER TABLE fleet_boot_offers ADD CONSTRAINT fleet_offer_sequence_unique UNIQUE (offer_sequence);

