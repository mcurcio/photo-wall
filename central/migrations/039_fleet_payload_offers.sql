-- Older Central writers omit this field and therefore remain explicitly legacy.
-- New writers set it to the inert payload format. Never reinterpret stored .deb
-- digests as payload digests during a rolling rollout or rollback.
ALTER TABLE fleet_app_policy
    ADD COLUMN target_format TEXT NOT NULL DEFAULT 'player-deb'
    CHECK (target_format IN ('player-deb','pw-player-data-v1'));
ALTER TABLE fleet_device_app_overrides
    ADD COLUMN target_format TEXT NOT NULL DEFAULT 'player-deb'
    CHECK (target_format IN ('player-deb','pw-player-data-v1'));

-- An old writer updating a new payload row does not know to change target_format.
-- Reject that mixed-version write instead of leaving a falsely typed digest.
CREATE FUNCTION fleet_validate_policy_artifact() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE release_sha TEXT;
DECLARE release_size BIGINT;
BEGIN
    IF NEW.target_tag IS NOT NULL THEN
        IF NEW.target_format = 'pw-player-data-v1' THEN
            SELECT payload_sha256,payload_size INTO release_sha,release_size
            FROM app_releases WHERE tag=NEW.target_tag;
        ELSE
            SELECT asset_sha256,asset_size INTO release_sha,release_size
            FROM app_releases WHERE tag=NEW.target_tag;
        END IF;
        IF release_sha IS DISTINCT FROM NEW.target_sha256
           OR release_size IS DISTINCT FROM NEW.target_size THEN
            RAISE EXCEPTION 'fleet policy artifact format mismatch'
                USING ERRCODE='23514', CONSTRAINT='fleet_policy_artifact_format';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER fleet_app_policy_artifact_guard
    BEFORE INSERT OR UPDATE ON fleet_app_policy
    FOR EACH ROW EXECUTE FUNCTION fleet_validate_policy_artifact();
CREATE TRIGGER fleet_device_override_artifact_guard
    BEFORE INSERT OR UPDATE ON fleet_device_app_overrides
    FOR EACH ROW EXECUTE FUNCTION fleet_validate_policy_artifact();
