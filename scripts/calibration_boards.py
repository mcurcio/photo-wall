"""Draw both calibration boards with OpenCV and write them into contracts/ (decision 0027; owner,
2026-10-14: "Make sure that you are using standard libraries and not building the algorithm").

The Pi and `contracts` never import OpenCV, so the boards are drawn here, at build time, by
cv2.aruco.CharucoBoard.generateImage (scripts/calibration_target/boards.py `charuco_board`) at
SQUARE_PX a square, with the squares the layout leaves out painted per
contracts.calibration_target `square` (WHITE 255, GREY `grey_code`, QR 255, RULER 0 with its
`ruler_steps`), and written as contracts/calibration_boards.py (stdlib data: zlib-compressed,
base85 text). tests/test_calibration_boards.py regenerates both and compares the file's bytes.

    python -m scripts.calibration_boards            # rewrite contracts/calibration_boards.py
    python -m scripts.calibration_boards --check    # exit 1 when the file differs from a fresh draw
"""
from __future__ import annotations

import argparse
import base64
import sys
import zlib
from collections.abc import Sequence
from pathlib import Path
from typing import Final

import numpy as np

from contracts.calibration_target import (
    PAPER_COLUMNS,
    PAPER_ROWS,
    SCREEN_COLUMNS_MAX,
    SCREEN_ROWS,
    SQUARE_PX,
    Raster,
    Square,
    Surface,
    grey_code,
    qr_copies,
    ruler_steps,
    square,
)
from scripts.calibration_target.boards import charuco_board

GENERATED: Final = Path(__file__).resolve().parents[1] / "contracts" / "calibration_boards.py"
_COMMAND: Final = "python -m scripts.calibration_boards"
_WIDTH: Final = 96          # a data line's characters, inside its quotes and indent (under 100 columns)


def screen_raster() -> Raster:
    """The whole screen board (SCREEN_COLUMNS_MAX x SCREEN_ROWS squares): charuco_board(SCREEN).
    generateImage((columns * SQUARE_PX, rows * SQUARE_PX), marginSize=0, borderBits=1), then every
    non-MARKER, non-BLACK square painted as `square` says (QR squares 255; RULER squares 0, then
    each `ruler_steps` step at its code). Deterministic. Pure."""
    image = _drawn(Surface.SCREEN, SCREEN_COLUMNS_MAX, SCREEN_ROWS)
    for copy in qr_copies(SCREEN_COLUMNS_MAX):
        for step in ruler_steps(copy):
            image[_px(step.top):_px(step.bottom), _px(step.left):_px(step.right)] = step.code
    return _raster(image)


def paper_raster() -> Raster:
    """The whole paper board (PAPER_COLUMNS x PAPER_ROWS squares), drawn as `screen_raster` with
    its WHITE squares painted 255. Deterministic. Pure."""
    return _raster(_drawn(Surface.PAPER, PAPER_COLUMNS, PAPER_ROWS))


def module_text(screen: Raster, paper: Raster) -> str:
    """contracts/calibration_boards.py's whole text: a docstring saying it is generated by this
    script (never edited by hand), stdlib imports only, and `SCREEN` and `PAPER`, each
    Final[tuple[int, int, bytes]] (width, height, pixels) decoded at import from
    zlib.compress(pixels, 9) as base85 text, wrapped under 100 columns. The same text for the same
    rasters. Pure."""
    return "\n".join([
        '"""The calibration boards\' rasters (decision 0027), GENERATED by scripts/calibration_boards.py:',
        "never edit by hand; rewrite with",
        "",
        f"    {_COMMAND}",
        "",
        "Each board is (width, height, pixels): one byte a pixel, row-major, the top row first",
        "(contracts.calibration_target `Raster`, read through `board_raster`).",
        '"""',
        "import base64",
        "import zlib",
        "from typing import Final",
        "",
        *_data_lines("_SCREEN", screen),
        *_data_lines("_PAPER", paper),
        "",
        "SCREEN: Final[tuple[int, int, bytes]] = (",
        f"    {screen.width}, {screen.height}, zlib.decompress(base64.b85decode(_SCREEN)))",
        "PAPER: Final[tuple[int, int, bytes]] = (",
        f"    {paper.width}, {paper.height}, zlib.decompress(base64.b85decode(_PAPER)))",
        "",
    ])


def main(argv: Sequence[str] | None = None) -> int:
    """Write module_text(screen_raster(), paper_raster()) to GENERATED and return 0; with
    `--check`, write nothing and return 1 when GENERATED's text differs (naming the command that
    rewrites it on stderr), else 0."""
    parser = argparse.ArgumentParser(prog=_COMMAND, description="Draw both calibration boards.")
    parser.add_argument("--check", action="store_true", help="exit 1 when the file is stale")
    check = parser.parse_args(argv).check
    text = module_text(screen_raster(), paper_raster())
    if not check:
        GENERATED.write_text(text, encoding="utf-8")
        return 0
    if not GENERATED.exists() or GENERATED.read_text(encoding="utf-8") != text:
        print(f"{GENERATED.name} differs from a fresh draw; rewrite it with: {_COMMAND}", file=sys.stderr)
        return 1
    return 0


def _drawn(surface: Surface, columns: int, rows: int) -> np.ndarray:
    """OpenCV's drawing of `surface`'s whole board, each square that is not MARKER or BLACK
    painted flat: WHITE, QR 255; GREY its code; RULER 0 (its steps come after)."""
    image = charuco_board(surface).generateImage(
        (columns * SQUARE_PX, rows * SQUARE_PX), marginSize=0, borderBits=1)
    for row in range(rows):
        for column in range(columns):
            kind = square(surface, row, column)
            if kind in (Square.MARKER, Square.BLACK):
                continue
            value = {Square.WHITE: 255, Square.QR: 255, Square.RULER: 0}.get(kind)
            image[row * SQUARE_PX:(row + 1) * SQUARE_PX, column * SQUARE_PX:(column + 1) * SQUARE_PX] = (
                grey_code(row, column) if value is None else value)
    return image


def _px(squares: float) -> int:
    """A distance in squares as whole raster pixels (the layout keeps every edge on one)."""
    pixels = squares * SQUARE_PX
    if pixels != round(pixels):
        raise ValueError("ruler_px")
    return round(pixels)


def _raster(image: np.ndarray) -> Raster:
    height, width = image.shape
    return Raster(width, height, image.astype(np.uint8).tobytes())


def _data_lines(name: str, raster: Raster) -> list[str]:
    """`name` = the raster's pixels, zlib-compressed and base85 text, wrapped in quoted lines."""
    text = base64.b85encode(zlib.compress(raster.pixels, 9)).decode("ascii")
    width = _WIDTH - 6
    chunks = (text[start:start + width] for start in range(0, len(text), width))
    return [f"{name}: Final = (", *(f'    "{chunk}"' for chunk in chunks), ")"]


if __name__ == "__main__":
    raise SystemExit(main())
