"""Write the console's TypeScript contract from Central's: central.console_contract.console_contract()
turned into central/console/src/generated/contract.ts, so the console's types, limits, patterns,
constants and refusal codes have one home, in Python.

What the file holds, for a contract of {"schemas", "constants", "refusals"}:

- one exported type per schema and per `$defs` entry, with no description (a model's docstring
  stays in Central's source): an object is an interface (a `const` field, a discriminator such as
  `kind` or `operation`, is always present), a union is a TS union, an enum a union of its values,
  a non-object schema a named type: a table entry (as RoomLight), or an alias pydantic titles
  itself (`Field(title="RoomLightId")`, a title its field would not have). An inline schema equal
  to a named alias is written as that alias;
- `LIMITS`: every bound a field or alias carries (minimum, maximum, exclusive bounds, multipleOf,
  item and length caps, pattern), by type then field, so a form steps and checks by Central's own;
- `PATTERNS`: each named alias's pattern;
- `CONSTANTS`, as the contract gives them;
- `REFUSALS`, each context's closed refusal codes, with `<Context>Refusal` the union of one
  context's codes.

The same contract always writes the same text (keys sorted, numbers in their shortest form).

    python -m scripts.console_types            # rewrite the file when it differs
    python -m scripts.console_types --check    # exit 1 when the committed file differs from a fresh write
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from collections.abc import Mapping, Sequence
from pathlib import Path
from typing import Any, Final

GENERATED: Final = Path(__file__).resolve().parents[1] / "central" / "console" / "src" / "generated" / "contract.ts"
_COMMAND: Final = "python -m scripts.console_types"
_IDENTIFIER: Final = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")
_TYPE_NAME: Final = re.compile(r"^[A-Z][A-Za-z0-9]*$")
_BOUNDS: Final = ("minimum", "maximum", "exclusiveMinimum", "exclusiveMaximum", "multipleOf", "minItems",
                  "maxItems", "minLength", "maxLength", "maxProperties", "pattern")
_NOTES: Final = ("title", "description", "default", "examples")    # never part of a type's shape

Schema = Mapping[str, Any]


class ContractError(ValueError):
    """The contract cannot be written as TypeScript (two different schemas under one name, a
    reference to nothing, a shape this writer does not know)."""


def contract_text(contract: Mapping[str, Any]) -> str:
    """The TypeScript module for `contract`. Deterministic. Pure."""
    definitions = _definitions(contract.get("schemas", {}))
    definitions.update(_titled_aliases(definitions))
    aliases = {name: _shape(schema) for name, schema in definitions.items() if not _is_object(schema)}
    writer = _Writer(definitions, aliases)
    lines = [
        "// GENERATED by `python -m scripts.console_types` from central/console_contract.py: never edit by hand.",
        "// Central's types, limits, patterns, constants and refusal codes for the console (one home, in Python).",
        "/* eslint-disable */",
        "",
    ]
    for name in sorted(definitions):
        lines.extend(writer.declaration(name, definitions[name]))
        lines.append("")
    lines.append(f"export const LIMITS = {_literal(writer.limits(), 0)} as const;")
    lines.append("")
    patterns = {name: schema["pattern"] for name, schema in sorted(definitions.items())
                if not _is_object(schema) and "pattern" in schema}
    lines.append(f"export const PATTERNS = {_literal(patterns, 0)} as const;")
    lines.append("")
    constants = dict(sorted(contract.get("constants", {}).items()))
    lines.append(f"export const CONSTANTS = {_literal(constants, 0)} as const;")
    lines.append("")
    refusals = {context: list(codes) for context, codes in sorted(contract.get("refusals", {}).items())}
    lines.append(f"export const REFUSALS = {_literal(refusals, 0)} as const;")
    for context in refusals:
        name = "".join(part.capitalize() for part in re.split(r"[_\-\s]+", context)) + "Refusal"
        if name in definitions:
            if set(_enum_values(definitions[name])) != set(refusals[context]):
                raise ContractError(f"{name}: the schema and the refusals of {context!r} differ")
            continue
        lines.append(f'export type {name} = (typeof REFUSALS)["{context}"][number];')
    return "\n".join(lines) + "\n"


def _definitions(schemas: Mapping[str, Schema]) -> dict[str, Schema]:
    """Every named schema: each table entry under its name and every `$defs` entry under its own,
    one schema a name (the same schema reached twice is one; two different ones raise)."""
    found: dict[str, Schema] = {}

    def add(name: str, schema: Schema) -> None:
        if not _IDENTIFIER.match(name):
            raise ContractError(f"{name!r} is not a TypeScript name")
        body = {key: value for key, value in schema.items() if key != "$defs"}
        if name in found and _shape(found[name]) != _shape(body):
            raise ContractError(f"two different schemas are named {name}")
        found.setdefault(name, body)

    for name, schema in sorted(schemas.items()):
        for inner, definition in sorted(schema.get("$defs", {}).items()):
            add(inner, definition)
        add(name, schema)
    return found


def _titled_aliases(definitions: Mapping[str, Schema]) -> dict[str, Schema]:
    """Every alias a schema names by its own title (pydantic's `Field(title=...)` on an Annotated
    type, as RoomLightId): an inline scalar or union whose title is a type name and is not the title
    pydantic gives its field anyway. One shape a title; the table's own names win."""
    found: dict[str, Schema] = {}

    def visit(schema: Any, field: str | None) -> None:
        if not isinstance(schema, Mapping):
            return
        title = schema.get("title")
        named = (isinstance(title, str) and _TYPE_NAME.match(title) is not None and "$ref" not in schema
                 and not _is_object(schema) and (field is None or title != _auto_title(field)))
        if named and title not in definitions:
            body = {key: value for key, value in schema.items() if key not in ("description", "default", "examples")}
            if title in found and _shape(found[title]) != _shape(body):
                raise ContractError(f"two different schemas are titled {title}")
            found.setdefault(title, body)
        for key, value in schema.items():
            if key == "properties":
                for name, inner in value.items():
                    visit(inner, name)
            elif key in ("items", "additionalProperties"):
                visit(value, None)
            elif key in ("anyOf", "oneOf", "allOf", "prefixItems"):
                for inner in value:
                    visit(inner, None)
            elif key == "patternProperties":
                for inner in value.values():
                    visit(inner, None)

    for name in sorted(definitions):
        visit(definitions[name], None if _is_object(definitions[name]) else name)
    return dict(sorted(found.items()))


def _shape(schema: Any) -> Any:
    """`schema` without its notes (title, description, default, examples), for comparison."""
    if isinstance(schema, Mapping):
        return {key: _shape(value) for key, value in sorted(schema.items()) if key not in _NOTES and key != "$defs"}
    if isinstance(schema, list):
        return [_shape(value) for value in schema]
    return schema


def _is_object(schema: Schema) -> bool:
    return schema.get("type") == "object" and "properties" in schema


def _enum_values(schema: Schema) -> list[Any]:
    return list(schema.get("enum", []))


def _auto_title(field: str) -> str:
    """The title pydantic gives a field it names nothing else: "heard_at" is "Heard At"."""
    return field.replace("_", " ").title()


class _Writer:
    def __init__(self, definitions: Mapping[str, Schema], aliases: Mapping[str, Any]) -> None:
        self._definitions = definitions
        self._aliases = aliases

    def declaration(self, name: str, schema: Schema) -> list[str]:
        lines: list[str] = []
        if _is_object(schema):
            lines.append(f"export interface {name} {{")
            required = set(schema.get("required", ()))
            for field, inner in schema["properties"].items():
                optional = field not in required and "const" not in inner
                key = field if _IDENTIFIER.match(field) else json.dumps(field)
                lines.append(f"  {key}{'?' if optional else ''}: {self.type(inner, field)};")
            lines.append("}")
        else:
            lines.append(f"export type {name} = {self.type(schema, None, top=True)};")
        return lines

    def type(self, schema: Schema, field: str | None, *, top: bool = False) -> str:
        """The TypeScript type of `schema` (a field's when `field` names it)."""
        if "$ref" in schema:
            return self._ref(schema["$ref"])
        if not top:
            named = self._alias(schema, field)
            if named is not None:
                return named
        if "const" in schema:
            return _literal(schema["const"], 0)
        if "enum" in schema:
            return " | ".join(_literal(value, 0) for value in schema["enum"])
        for union in ("oneOf", "anyOf"):
            if union in schema:
                parts = [self.type(part, None) for part in schema[union]]
                return " | ".join(dict.fromkeys(_grouped(part) for part in parts))
        kind = schema.get("type")
        if isinstance(kind, list):
            return " | ".join(self.type({**schema, "type": each}, None) for each in kind)
        if kind in ("number", "integer"):
            return "number"
        if kind == "string":
            return "string"
        if kind == "boolean":
            return "boolean"
        if kind == "null":
            return "null"
        if kind == "array":
            if "prefixItems" in schema:
                return f"[{', '.join(self.type(item, None) for item in schema['prefixItems'])}]"
            items = schema.get("items")
            return f"{_grouped(self.type(items, None))}[]" if items else "unknown[]"
        if kind == "object":
            values = schema.get("additionalProperties")
            patterned = schema.get("patternProperties", {})
            if patterned:
                key_pattern, values = next(iter(sorted(patterned.items())))
                key = self._pattern_alias(key_pattern) or "string"
            else:
                key = "string"
            value = self.type(values, None) if isinstance(values, Mapping) else "unknown"
            return f"Record<{key}, {value}>"
        if not _shape(schema):
            return "unknown"
        raise ContractError(f"no TypeScript for the schema {json.dumps(schema, sort_keys=True)}")

    def limits(self) -> dict[str, dict[str, Any]]:
        """Every bound, by type then field (an alias's own under its name, as `value`)."""
        found: dict[str, dict[str, Any]] = {}
        for name, schema in sorted(self._definitions.items()):
            if _is_object(schema):
                fields = {field: _bounds(self._resolved(inner)) for field, inner in sorted(schema["properties"].items())}
                fields = {field: bounds for field, bounds in fields.items() if bounds}
                if fields:
                    found[name] = fields
            elif _bounds(schema):
                found[name] = {"value": _bounds(schema)}
        return found

    def _resolved(self, schema: Schema) -> Schema:
        """A field's schema, through one `$ref` to an alias (a field typed by a named alias keeps
        its alias's bounds)."""
        if "$ref" in schema:
            name = self._ref(schema["$ref"])
            target = self._definitions[name]
            return {} if _is_object(target) else target
        return schema

    def _ref(self, ref: str) -> str:
        name = ref.rsplit("/", 1)[-1]
        if name not in self._definitions:
            raise ContractError(f"{ref} names no schema")
        return name

    def _alias(self, schema: Schema, field: str | None) -> str | None:
        """The named alias `schema` is: one whose shape it has, under that alias's title (or with
        no title of its own); None for any other."""
        title = schema.get("title")
        shape = _shape(schema)
        if isinstance(title, str) and title in self._aliases and self._aliases[title] == shape:
            return title
        if (title is None or (field is not None and title == _auto_title(field))) and shape:
            matches = [name for name, alias in self._aliases.items() if alias == shape]
            if len(matches) == 1 and ("oneOf" in schema or "anyOf" in schema):
                return matches[0]
        return None

    def _pattern_alias(self, pattern: str) -> str | None:
        matches = [name for name, alias in sorted(self._aliases.items())
                   if alias == {"pattern": pattern, "type": "string"}]
        return matches[0] if len(matches) == 1 else None


def _bounds(schema: Schema) -> dict[str, Any]:
    found = {key: schema[key] for key in _BOUNDS if key in schema}
    if found and schema.get("type") == "integer":
        found["integer"] = True
    return found


def _grouped(text: str) -> str:
    return f"({text})" if " | " in text else text


def _literal(value: Any, depth: int) -> str:
    """`value` as a TypeScript literal: objects over several lines with sorted keys, numbers in
    their shortest form (200000.0 is 200000)."""
    pad = "  " * (depth + 1)
    if isinstance(value, bool) or value is None:
        return json.dumps(value)
    if isinstance(value, float):
        return str(int(value)) if value.is_integer() else repr(value)
    if isinstance(value, int):
        return str(value)
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, Mapping):
        if not value:
            return "{}"
        items = []
        for key in sorted(value):
            name = key if _IDENTIFIER.match(key) else json.dumps(key)
            items.append(f"{pad}{name}: {_literal(value[key], depth + 1)},")
        return "{\n" + "\n".join(items) + "\n" + "  " * depth + "}"
    if isinstance(value, Sequence):
        if not value:
            return "[]"
        return "[\n" + "\n".join(f"{pad}{_literal(item, depth + 1)}," for item in value) + "\n" + "  " * depth + "]"
    raise ContractError(f"no TypeScript literal for {value!r}")


def written() -> str:
    """The file a fresh write gives, from Central's contract now."""
    from central.console_contract import console_contract

    contract = console_contract()
    if not isinstance(contract, Mapping):
        raise ContractError("central.console_contract.console_contract() answered no contract")
    return contract_text(contract)


def main(argv: Sequence[str] | None = None) -> int:
    """Rewrite GENERATED when it differs and return 0; with `--check`, write nothing and return 1
    when it is missing or differs (naming the command that rewrites it on stderr), else 0."""
    parser = argparse.ArgumentParser(prog=_COMMAND, description="Write the console's contract from Central's.")
    parser.add_argument("--check", action="store_true", help="exit 1 when the committed file is stale")
    check = parser.parse_args(argv).check
    text = written()
    current = GENERATED.read_text(encoding="utf-8") if GENERATED.exists() else None
    if current == text:
        return 0
    if check:
        print(f"{GENERATED.name} differs from Central's contract; rewrite it with: {_COMMAND}", file=sys.stderr)
        return 1
    GENERATED.parent.mkdir(parents=True, exist_ok=True)
    GENERATED.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
