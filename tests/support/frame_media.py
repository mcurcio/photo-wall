def grant(registry, repository: MediaRepository, variant: Variant, *, secured: bool = False,
          frame_id: str = "portrait"):
    """An enrolled Player bound to `frame_id`, offered (or, `secured`, locked) one layer that
    shows `variant`, pinned as coordination pins it. Returns (player, key, plan)."""
    player, key, _ = enroll(registry)
    registry.bind(frame_id, player["player_id"], "HDMI-A-1", expected_generation=0)
    save_position(registry, frame_id)
    binding = registry.bindings_for(player["player_id"], 1)[0]
    layer = Layer(assignment_id="assignment", run_id="run", output_id=binding.output_id,
                  frame_id=binding.frame_id, binding_generation=binding.generation,
                  start=1000, end=1200, media_origin=1000, variant=variant, crop=CENTRED)
    plan = Plan(plan_id="plan", revision=1, player_id=player["player_id"], authority_epoch=1,
                issued_at=1000, valid_from=1000, valid_until=1200, bindings=(binding,),
                layers=(layer,))
    with repository.transaction() as conn:
        if secured:
            conn.execute("INSERT INTO assignment_locks VALUES(%s,1,%s,%s,1000,1200)",
                         (player["player_id"], layer.assignment_id,
                          Jsonb(layer.model_dump(mode="json"))))
            conn.execute("INSERT INTO media_references(owner,variant_key,expires_at) "
                         "VALUES(%s,%s,1200)",
                         (f"secured:{player['player_id']}:1:{layer.assignment_id}", variant.key))
        else:
            Coordinator(registry.db, registry.clock, media=repository)._offer(
                conn, plan, {layer.assignment_id: "group"})
    return player, key, plan


def a_frame(registry, frame_id: str = "portrait") -> None:
    """A Frame, so the wall has a need and a recipe (`MediaRepository.wall_recipe_in`)."""
    frame(registry, frame_id)


class FakeLibrary:
    """`LibraryWorkerStore`'s media maker half: one connection, no measured copies."""

    def __init__(self) -> None:
        self.recorded: list[tuple[str, object]] = []

    def connection_secret(self, connection_ref: str) -> ConnectionSecret:
        return ConnectionSecret(connection_ref=connection_ref, base_url="https://immich.invalid",
                                api_key="test-only")

    def copy_sizes(self, asset_id: str) -> dict:
        return {}

    def record_copies(self, asset_id: str, measured) -> None:
        self.recorded.append((asset_id, measured))


class FakeClient:
    """A library client whose every fetch writes `original` and says it was the preview."""

    def __init__(self, original: bytes) -> None:
        self.original = original
        self.fetches = 0

    async def fetch_rendition(self, asset, *, plan, needs, destination: Path) -> FetchedRendition:
        self.fetches += 1
        with open(destination, "xb") as stream:
            stream.write(self.original)
        return FetchedRendition(path=destination, rendition="preview", media_type="image/jpeg",
                                size=len(self.original),
                                sha256=hashlib.sha256(self.original).hexdigest(),
                                width=asset.width, height=asset.height, measured=())

    async def close(self) -> None:
        pass


class FakePreparer:
    """Writes the next of `outputs` as each preparation's bytes (a re-make may differ)."""

    def __init__(self, outputs: Iterator[bytes]) -> None:
        self.outputs = outputs
        self.recipes: list = []

    async def prepare_rendition(self, asset, rendition, destination: Path, *, recipe=None):
        self.recipes.append(recipe)
        data = next(self.outputs)
        with open(destination, "xb") as stream:
            stream.write(data)
        return PreparedMedia(
            path=destination, original_sha256=rendition.sha256, build=BUILD,
            made_from=rendition.rendition,
            variant=Variant(sha256=hashlib.sha256(data).hexdigest(), size=len(data),
                            media_type="image/jpeg", width=asset.width, height=asset.height))


def media_maker(repository: MediaRepository, cache_root: Path, *, original: bytes,
                outputs: Iterator[bytes]) -> tuple[MediaMaker, FakeClient, FakePreparer]:
    client, preparer = FakeClient(original), FakePreparer(outputs)

    async def connect(_secret):
        return client

    from central.assets.layout import CacheLayout
    maker = MediaMaker(store=CacheStore(CacheLayout(cache_root)), records=repository.records,
                       transactions=PgTransactions(repository.db),
                       inputs=repository.variant_inputs, library=FakeLibrary(), client=connect,
                       preparer=preparer)
    return maker, client, preparer


class InlinePublisher:
    """A `Publisher` that runs each published asset job's handler at once and records its facts
    as the job runtime does (the read path's miss, with no worker process)."""

    def __init__(self, handler: Handler, repository: MediaRepository) -> None:
        self.handler = handler
        self.repository = repository
        self.published: list[Job] = []

    async def publish_now(self, job, *, retry_terminal: bool = False):
        self.published.append(job)
        facts = await self.handler.handle(job)
        assert isinstance(facts, AssetReady)
        with self.repository.db.transaction() as conn:
            from central.infra.transactions import PgTransaction
            self.repository.records.record_produced(PgTransaction(conn), asset_key(job), facts)
        return SettledHandle(Ready(facts))

    def publish(self, job, *, within, retry_terminal: bool = False):
        raise AssertionError("a pinned read publishes only on a miss")


def seed_variant(registry, asset_id: str, sha256: str, *, size: int = 10, width: int = 1080,
                 height: int = 1920, media_type: str = "image/jpeg",
                 duration: float | None = None) -> Variant:
    """A made media variant of `asset_id` under the wall's current recipe (its record with
    produced facts, as `PrepareMedia` leaves it; no file): what a Planner hydrates. The wall
    needs a Frame first."""
    from central.assets.frame_media import VARIANT_REFERENCE, variant_asset_key
    from central.db import ProcessTransactionClock
    from central.infra.transactions import PgTransaction
    from central.kernel.assets import MediaReady
    from central.kernel.types import media_variant_key

    repository = MediaRepository(registry.db, registry.clock,
                                 times=ProcessTransactionClock(registry.clock))
    with registry.db.transaction() as conn:
        recipe = repository.wall_recipe_in(conn, record=True)
        assert recipe is not None, "a variant needs a Frame (the wall's need)"
        key = media_variant_key(asset_id, recipe)
        tx = PgTransaction(conn)
        repository.records.reference(tx, variant_asset_key(key), VARIANT_REFERENCE)
        repository.records.record_produced(tx, variant_asset_key(key), MediaReady(
            size=size, sha256=sha256, media_type=media_type, width=width, height=height,
            duration=duration, made_from="preview"))
        return repository.variants_in(conn, (key,))[key]
