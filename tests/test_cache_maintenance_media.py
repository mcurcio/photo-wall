HOURS = 3600
SIZE = 100  # every variant's file


def budget(registry, root, budget_bytes: int) -> MediaCacheBudget:
    return MediaCacheBudget(
        store=CacheStore(CacheLayout(root)),
        use=PgMediaVariantUse(times=ProcessTransactionClock(registry.clock)),
        transactions=PgTransactions(registry.db),
        settings=CacheSettings(media_budget_bytes=budget_bytes))


def age(path, seconds: float = 2 * HOURS) -> None:
    """Older than every grace (the file was installed long ago)."""
    then = time.time() - seconds
    os.utime(path, (then, then))


class Variants:
    """`count` photos on a one-Frame wall, each prepared into a `SIZE`-byte file, aged."""

    def __init__(self, registry, root, count: int) -> None:
        self.registry, self.root = registry, root
        self.repository = MediaRepository(registry.db, registry.clock,
                                          times=ProcessTransactionClock(registry.clock))
        a_frame(registry)
        photos = tuple(photo(f"photo-{n}", taken_at=900 + n) for n in range(count))
        seed_pool(registry, "source:1", photos)
        cache = MediaCache(self.repository, root)
        self.variants = [make_variant(cache, request_photo(cache, p.asset_id),
                                      bytes([n]) * SIZE, width=1080, height=1920)
                         for n, p in enumerate(photos)]
        for variant in self.variants:
            age(self.path(variant))

    def path(self, variant):
        return CacheLayout(self.root).path(variant_asset_key(variant.key),
                                           produced(self, variant.key))

    def served(self, variant, at: float) -> None:
        with self.registry.db.transaction() as conn:
            conn.execute("UPDATE assets SET last_served_at=%s WHERE kind=%s AND identity=%s",
                         (at, AssetKind.MEDIA_VARIANT.value, variant.key))

    def pin(self, variant, owner: str, expires_at: float) -> None:
        with self.registry.db.transaction() as conn:
            conn.execute("INSERT INTO media_references(owner,variant_key,expires_at) "
                         "VALUES(%s,%s,%s)", (owner, variant.key, expires_at))

    def kept(self) -> list[bool]:
        return [self.path(variant).exists() for variant in self.variants]


def test_pinned_files_survive_over_budget(registry, tmp_path):
    """Mutation probe: ignore pins (`pinned` answers False) -> the pinned files are evicted and
    this test fails."""
    wall = Variants(registry, tmp_path, 4)
    offered, locked, expired, loose = wall.variants
    grant(registry, wall.repository, offered)              # coordination's offer pin
    wall.pin(locked, "secured:player:1:assignment", 1200)  # a secured lock's pin
    wall.pin(expired, "transfer:" + "0" * 32, 900)         # expired before the clock's 1000
    removed = budget(registry, tmp_path, 0).enforce()
    assert wall.kept() == [True, True, False, False]
    assert sorted(path.name for path in removed) == sorted(
        wall.path(v).name for v in (expired, loose))


def test_the_least_recently_served_files_go_first_until_under_budget(registry, tmp_path):
    wall = Variants(registry, tmp_path, 4)
    never, old, recent, middle = wall.variants
    wall.served(old, 10)
    wall.served(recent, 30)
    wall.served(middle, 20)
    budget(registry, tmp_path, 2 * SIZE).enforce()
    assert wall.kept() == [False, False, True, True]
    budget(registry, tmp_path, 2 * SIZE).enforce()  # under budget: nothing more goes
    assert wall.kept() == [False, False, True, True]


def test_under_budget_nothing_is_evicted(registry, tmp_path):
    wall = Variants(registry, tmp_path, 3)
    assert budget(registry, tmp_path, 3 * SIZE).enforce() == []
    assert wall.kept() == [True, True, True]


def test_temp_files_and_just_installed_files_get_a_grace_period(registry, tmp_path):
    wall = Variants(registry, tmp_path, 1)
    directory = CacheLayout(tmp_path).directory(AssetKind.MEDIA_VARIANT)
    idle, live = directory / f"{TEMP_PREFIX}idle", directory / f"{TEMP_PREFIX}live"
    idle.write_bytes(b"i" * SIZE)
    live.write_bytes(b"l" * SIZE)
    age(idle)
    fresh = directory / ("f" * 64)  # installed, its record not yet committed
    fresh.write_bytes(b"f" * SIZE)
    budget(registry, tmp_path, 0).enforce()
    assert not idle.exists()
    assert live.exists() and fresh.exists()
    assert wall.kept() == [False]


def test_an_evicted_file_is_re_made_on_its_next_get(registry, tmp_path):
    wall = Wall(registry, tmp_path, iter([FIRST, SECOND]))
    variant = wall.first_making()
    path = CacheLayout(tmp_path).path(variant_asset_key(variant.key),
                                      produced(wall, variant.key))
    age(path)
    assert budget(registry, tmp_path, 0).enforce() == [path]
    assert not path.exists()
    player, _, _ = grant(registry, wall.repository, variant)  # planned again: pinned
    with TestClient(wall.app()) as client:
        response = client.get(f"/v1/media/{variant.asset_id}/{variant.recipe_id}",
                              headers={"Authorization": f"Bearer {player['token']}"})
    assert response.status_code == 200 and response.content == SECOND
    assert wall.client.fetches == 2  # the first making and one re-make


