# The rule over a recorded fake of its records (no database): the pin re-read under the lock.

class _Tx:
    state = "open"


class _Transactions:
    @contextmanager
    def begin(self):
        yield _Tx()


class _Use:
    """`uses` answers what a first read saw; `pinned` answers now (after `pinned_since`)."""

    def __init__(self, seen: dict[str, VariantFileUse], pinned_since: set[str]) -> None:
        self.seen, self.pinned_since, self.locks = seen, pinned_since, 0

    def uses(self, tx):
        return self.seen

    def lock(self, tx):
        self.locks += 1

    def pinned(self, tx, digest):
        return digest in self.pinned_since or self.seen.get(
            digest, VariantFileUse(False, None)).pinned


def _files(root, names):
    directory = CacheLayout(root).directory(AssetKind.MEDIA_VARIANT)
    directory.mkdir(parents=True)
    paths = []
    for name in names:
        path = directory / name
        path.write_bytes(b"x" * SIZE)
        age(path)
        paths.append(path)
    return paths


def test_a_pin_committed_after_the_read_spares_the_file(tmp_path):
    """Mutation probe: ignore pins (drop the `pinned` filter and the re-read under the lock) ->
    the pinned files go and this test fails."""
    held, late, loose = (c * 64 for c in "abc")
    paths = _files(tmp_path, (held, late, loose))
    use = _Use({held: VariantFileUse(True, None), late: VariantFileUse(False, 1.0),
                loose: VariantFileUse(False, 2.0)}, pinned_since={late})
    rule = MediaCacheBudget(store=CacheStore(CacheLayout(tmp_path)), use=use,
                            transactions=_Transactions(), settings=CacheSettings(0))
    assert rule.enforce() == [paths[2]]
    assert [path.exists() for path in paths] == [True, True, False]
    assert use.locks == 2  # each unlink decided under the media lock
