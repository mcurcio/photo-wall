"""One cache budget for media variants (follow-up to 5a, slice S5): every file a live pin holds is
kept; the others go, least recently served first, until `media/` is under
`CacheSettings.media_budget_bytes`; a temp file (and a file just installed) gets a grace period;
an evicted file is re-made on its next GET. Real PostgreSQL, the real app, generated bytes."""

