ORIGINAL = b"public synthetic original bytes"
FIRST = b"the first making's bytes"


def repr_digest(data: bytes) -> str:
    return "sha-256=:" + base64.b64encode(hashlib.sha256(data).digest()).decode() + ":"


class Wall:
    """One Frame, one photo in a pool, and a maker whose preparations write `outputs` in turn."""

    def __init__(self, registry, root, outputs):
        self.registry, self.root = registry, root
        self.repository = MediaRepository(registry.db, registry.clock,
                                          times=ProcessTransactionClock(registry.clock))
        a_frame(registry)
        self.photo = photo("photo-1", taken_at=900)
        seed_pool(registry, "source:1", (self.photo,))
        self.maker, self.client, self.preparer = media_maker(
            self.repository, root, original=ORIGINAL, outputs=outputs)

    def first_making(self):
        """Coordination's request, then one run of `PrepareMedia` as the job runtime runs it."""
        key = request_photo(MediaCache(self.repository, self.root), self.photo.asset_id)
        facts = asyncio.run(self.maker.handle(PrepareMedia(key=key)))
        with self.registry.db.transaction() as conn:
            self.repository.records.record_produced(PgTransaction(conn),
                                                    asset_key(PrepareMedia(key=key)), facts)
            return self.repository.variants_in(conn, (key,))[key]

    def app(self, publisher=None):
        content = build_content_services(self.registry.db, self.registry.clock,
                                         cache_root=self.root)
        reader = AssetReader(store=CacheStore(CacheLayout(self.root)), records=self.repository.records,
                             transactions=PgTransactions(self.registry.db),
                             publisher=publisher or InlinePublisher(self.maker, self.repository),
                             slots=WaiterSlots(8), clock=self.registry.clock)
        return create_app(self.registry.db, self.registry.clock, ADMIN, cache_root=self.root,
                          content=replace(content, frame_media_reader=reader))

    def transfers(self) -> int:
        with self.registry.db.transaction() as conn:
            return conn.execute("SELECT count(*) AS n FROM media_references "
                                "WHERE owner LIKE 'transfer:%'").fetchone()["n"]


@pytest.fixture
def wall(registry, tmp_path):
    return Wall(registry, tmp_path, itertools.repeat(FIRST))


def test_a_first_making_is_served_by_its_name(wall, registry):
    """Mutation probe: drop `media_authorized_in` -> the stranger's 403 test below fails."""
    variant = wall.first_making()
    player, _, _ = grant(registry, wall.repository, variant)
    url = f"/v1/media/{variant.asset_id}/{variant.recipe_id}"
    headers = {"Authorization": f"Bearer {player['token']}"}
    with TestClient(wall.app()) as client:
        assert client.get(url).status_code == 401
        assert client.get(url, headers={**headers, "Range": "bytes=0-4"}).status_code == 416
        response = client.get(url, headers=headers)
        assert response.status_code == 200
        assert response.content == FIRST
        assert response.headers["Repr-Digest"] == repr_digest(FIRST)
        assert response.headers["Content-Length"] == str(len(FIRST))
        assert response.headers["Cache-Control"] == "private, no-store"
    assert wall.client.fetches == 1  # served from the cache, never made twice
    assert wall.transfers() == 0  # every transfer pin is released with its body


def test_a_secured_lock_grants_its_variant(wall, registry):
    variant = wall.first_making()
    player, _, _ = grant(registry, wall.repository, variant, secured=True)
    with TestClient(wall.app()) as client:
        response = client.get(f"/v1/media/{variant.asset_id}/{variant.recipe_id}",
                              headers={"Authorization": f"Bearer {player['token']}"})
    assert response.status_code == 200 and response.content == FIRST


def test_another_players_media_unknown_names_and_retired_players_are_refused(wall, registry):
    """Mutation probe: skip `media_authorized_in` in `FrameMedia._resolve` -> the stranger is
    served and this test fails."""
    variant = wall.first_making()
    player, _, _ = grant(registry, wall.repository, variant)
    url = f"/v1/media/{variant.asset_id}/{variant.recipe_id}"
    stranger, _, _ = enroll(registry)
    with TestClient(wall.app()) as client:
        refused = client.get(url, headers={"Authorization": f"Bearer {stranger['token']}"})
        assert (refused.status_code, refused.json()) == (403, {"error": "media_forbidden"})
        headers = {"Authorization": f"Bearer {player['token']}"}
        unknown = client.get(f"/v1/media/{variant.asset_id}/{'0' * 64}", headers=headers)
        assert (unknown.status_code, unknown.json()) == (404, {"error": "media_unavailable"})
        assert client.get(f"/v1/media/not-an-asset/{variant.recipe_id}",
                          headers=headers).status_code == 404
        assert client.get("/v1/media/" + "0" * 64, headers=headers).status_code == 404
        registry.unbind("portrait", expected_generation=1)
        registry.retire(player["player_id"])
        assert client.get(url, headers=headers).status_code == 401
    assert wall.transfers() == 0


class StillMaking:
    """A `Publisher` whose re-make has not finished when the read stops waiting."""

    def __init__(self) -> None:
        self.published: list = []

    async def publish_now(self, job, *, retry_terminal: bool = False):
        self.published.append(job)
        return self

    async def wait(self, *, timeout):
        return Pending()


def test_a_miss_whose_re_make_does_not_finish_in_time_answers_503_and_releases_its_pin(
        wall, registry):
    """The file is gone and its re-make is still running when the read stops waiting: 503
    `media_unavailable` with a Retry-After, and the transfer pin the grant took is released."""
    variant = wall.first_making()
    player, _, _ = grant(registry, wall.repository, variant)
    with registry.db.transaction() as conn:
        produced = wall.repository.records.get(
            PgTransaction(conn), asset_key(PrepareMedia(key=variant.key))).produced
    CacheLayout(wall.root).path(asset_key(PrepareMedia(key=variant.key)), produced).unlink()
    publisher = StillMaking()
    with TestClient(wall.app(publisher)) as client:
        response = client.get(f"/v1/media/{variant.asset_id}/{variant.recipe_id}",
                              headers={"Authorization": f"Bearer {player['token']}"})
    assert (response.status_code, response.json()) == (503, {"error": "media_unavailable"})
    assert int(response.headers["Retry-After"]) > 0
    assert publisher.published == [PrepareMedia(key=variant.key)]
    assert wall.transfers() == 0


class StaleSessions(PostgresInstallationRepository):
    """The bearer's session as it was read at epoch 1, while the Player is now at epoch 2."""

    def authenticate_in(self, conn, token):
        identity = super().authenticate_in(conn, token)
        return None if identity is None else {**identity, "authority_epoch": 1}


def test_a_stale_epoch_answers_401(wall, registry):
    """Mutation probe: drop the epoch check (`configuration_in` at the Player's current epoch
    instead of the session's) -> the stale session is granted and this test fails."""
    variant = wall.first_making()
    player, _, _ = grant(registry, wall.repository, variant)
    with registry.db.transaction() as conn:
        conn.execute("UPDATE players SET authority_epoch=2 WHERE id=%s", (player["player_id"],))
    frame_media = FrameMedia(
        transactions=PgTransactions(registry.db), records=wall.repository.records,
        clock=registry.clock,
        grants=PgFrameMediaGrants(installation=StaleSessions(registry.clock),
                                  execution=PostgresExecutionRepository()))
    with pytest.raises(FrameMediaRefused) as refused:
        frame_media.resolve(player["token"], variant.key)
    assert (refused.value.code, refused.value.status) == ("unauthorized", 401)
