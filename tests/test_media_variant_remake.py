SECOND = b"a re-make's different bytes"


@pytest.fixture
def wall(registry, tmp_path):
    return Wall(registry, tmp_path, iter([FIRST, SECOND, SECOND]))


def produced(wall, key):
    with wall.registry.db.transaction() as conn:
        return wall.repository.records.get(PgTransaction(conn), variant_asset_key(key)).produced


def test_a_deleted_file_is_re_made_and_served_under_the_same_name(wall, registry):
    """Mutation probe: authorize only the plan's digest (`layer.variant.sha256` equal to the
    record's) -> the re-made bytes are refused and this test fails."""
    variant = wall.first_making()
    player, _, plan = grant(registry, wall.repository, variant)
    path = CacheLayout(wall.root).path(variant_asset_key(variant.key), produced(wall, variant.key))
    path.unlink()
    url = f"/v1/media/{variant.asset_id}/{variant.recipe_id}"
    headers = {"Authorization": f"Bearer {player['token']}"}
    with TestClient(wall.app()) as client:
        response = client.get(url, headers=headers)
        assert response.status_code == 200
        assert response.content == SECOND
        assert response.headers["Repr-Digest"] == repr_digest(SECOND)
        assert plan.layers[0].variant.sha256 == hashlib.sha256(FIRST).hexdigest()  # the plan's
        again = client.get(url, headers=headers)
        assert again.content == SECOND
    assert wall.client.fetches == 2  # the first making and one re-make, never a third
    remade = produced(wall, variant.key)
    assert (remade.sha256, remade.size) == (hashlib.sha256(SECOND).hexdigest(), len(SECOND))
    assert remade.made_from == "preview"
    # Both made by the variant's own recipe: the wall's 1920 step (follow-up S1).
    assert wall.preparer.recipes == [PreparationRecipe(image_long_edge=1920)] * 2


def test_the_player_accepts_a_re_made_copy_under_the_plan_s_name(wall, registry, tmp_path):
    """A deleted file is re-made, and the Player accepts different bytes: it fetches the plan's
    variant by name and checks the body against Central's `Repr-Digest` and `Content-Length`,
    not the plan's digest (a digest that differs from the plan's is still the same content).
    The real Player service and cache, the real app over ASGI, real PostgreSQL.

    Mutation probe 3: check the bytes against the plan's digest (`variant.sha256`, in
    `PlayerService.download`) -> the re-made bytes are refused and this test fails."""
    variant = wall.first_making()
    CacheLayout(wall.root).path(variant_asset_key(variant.key),
                                produced(wall, variant.key)).unlink()

    async def check():
        cache_dir = tmp_path / "player-cache"
        cache_dir.mkdir(mode=0o700)
        client = httpx.AsyncClient(transport=httpx.ASGITransport(app=wall.app()),
                                   trust_env=False)
        service = PlayerService(
            PlayerConfig(central_origin="http://central", cache_dir=str(cache_dir),
                         cache_bytes=1024**2),
            load_identity(), (OutputReport(output_id="HDMI-A-1", width_px=1920,
                                           height_px=1080),),
            RecordingRenderer(), immediate, find_central=finding("http://central"),
            trust=TRUST, clock=registry.clock, client=client, time_client=client,
            websocket_connect=False, boot_context=boot_context())
        try:
            await service.locate_central()
            await service.enroll()
            await service.hello_protocol()
            plan = offer(registry, wall.repository, variant,
                         service.registration.player_id)
            await service.poll_state()
            service._feedback()
            (job,) = service._jobs
            assert job.layer.variant.sha256 == hashlib.sha256(FIRST).hexdigest()  # the plan's
            assert await service.download(job)
            assert service.cache.path_for(plan.layers[0].variant).read_bytes() == SECOND
            assert service._feedback()[0].secured == ("assignment",)
        finally:
            await close(service)

    asyncio.run(check())
    assert wall.client.fetches == 2  # the first making and one re-make


def test_a_corrupt_file_is_discarded_and_re_made(wall, registry):
    variant = wall.first_making()
    player, _, _ = grant(registry, wall.repository, variant)
    path = CacheLayout(wall.root).path(variant_asset_key(variant.key), produced(wall, variant.key))
    path.write_bytes(b"x" * len(FIRST))  # same size, other bytes
    with TestClient(wall.app()) as client:
        response = client.get(f"/v1/media/{variant.asset_id}/{variant.recipe_id}",
                              headers={"Authorization": f"Bearer {player['token']}"})
    assert response.status_code == 200 and response.content == SECOND
    assert not path.exists()  # the corrupt file is gone, never served


def test_a_reader_holding_the_previous_facts_reads_the_previous_bytes(wall):
    """While a re-make is in flight a body matches the digest read with it: the re-make writes a
    new path, never the previous one.

    Mutation probe: name the file by the variant's key (a re-make writes over the previous
    path) -> the previous facts open nothing and this test fails."""
    variant = wall.first_making()
    key = variant_asset_key(variant.key)
    previous = produced(wall, variant.key)
    with wall.registry.db.transaction() as conn:  # a re-make is due (another reader's miss)
        conn.execute("UPDATE assets SET produced_size=NULL,produced_sha256=NULL,"
                     "produced_detail=NULL WHERE kind=%s AND identity=%s",
                     (AssetKind.MEDIA_VARIANT.value, variant.key))
    remade = asyncio.run(wall.maker.handle(PrepareMedia(key=variant.key)))
    store = CacheStore(CacheLayout(wall.root))
    opened = store.open(key, previous)
    assert opened is not None
    with os.fdopen(opened.fd, "rb") as body:
        assert hashlib.sha256(body.read()).hexdigest() == previous.sha256
    opened = store.open(key, remade)
    assert opened is not None
    with os.fdopen(opened.fd, "rb") as body:
        assert body.read() == SECOND


def test_a_whole_file_is_not_made_again(wall):
    variant = wall.first_making()
    facts = asyncio.run(wall.maker.handle(PrepareMedia(key=variant.key)))
    assert facts == produced(wall, variant.key)
    assert wall.client.fetches == 1


def test_a_legacy_variant_is_served_but_never_re_made(wall):
    variant = wall.first_making()
    with wall.registry.db.transaction() as conn:
        conn.execute("UPDATE asset_references SET owner='legacy-087',"
                     "locator_url='http://legacy.invalid/' WHERE kind=%s AND identity=%s",
                     (AssetKind.MEDIA_VARIANT.value, variant.key))
    assert asyncio.run(wall.maker.handle(PrepareMedia(key=variant.key))) == produced(
        wall, variant.key)
    CacheLayout(wall.root).path(variant_asset_key(variant.key),
                                produced(wall, variant.key)).unlink()
    with pytest.raises(TerminalFailure, match="legacy_variant"):
        asyncio.run(wall.maker.handle(PrepareMedia(key=variant.key)))
    assert wall.client.fetches == 1


def test_the_recipe_id_names_the_recipe_values_and_the_need_only():
    """The owner's open choice, default "drop": the renderer build is not in the name."""
    need = FrameNeed(aspect=1080 / 1920, width=1080, height=1920)
    assert recipe_id(PreparationRecipe(), need) == recipe_id(PreparationRecipe(), need)
    assert recipe_id(PreparationRecipe(), need) != recipe_id(
        PreparationRecipe(), need.model_copy(update={"width": 2160}))
    assert recipe_id(PreparationRecipe(), need) != recipe_id(
        PreparationRecipe(jpeg_quality=4), need)
